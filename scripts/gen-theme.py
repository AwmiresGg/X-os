#!/usr/bin/env python3
"""Generate theme files from ui/theme/tokens.json:

* ui/qml/XOS/Theme/Theme.qml               QML singleton for the X-OS shell and apps
* themes/plasma/color-schemes/XOS*.colors  KDE colour schemes (Dolphin, Settings, all Qt/KDE apps)

    scripts/gen-theme.py          # writes them
    scripts/gen-theme.py --check  # exit 1 if any is out of date (used by tests)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "ui/theme/tokens.json"
OUT = ROOT / "ui/qml/XOS/Theme/Theme.qml"
SCHEMES = ROOT / "themes/plasma/color-schemes"


def _rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")[-6:]          # drop alpha of #AARRGGBB
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def _mix(a: str, b: str, t: float) -> str:
    ra, rb = _rgb(a), _rgb(b)
    return "#%02X%02X%02X" % tuple(round(x + (y - x) * t) for x, y in zip(ra, rb))


def _c(h: str) -> str:
    return "%d,%d,%d" % _rgb(h)


def color_scheme(mode: str) -> str:
    """A complete KDE colour scheme. Window and toolbar ("Header") share one surface for the
    unified, calm look; selections are a softened accent, never a saturated block."""
    t = json.loads(TOKENS.read_text())["color"]
    c = t[mode]
    dark = mode == "dark"
    window, view, button = c["surface1"], c["surface0"], c["surface2"]
    sel = _mix(c["accent"], c["surface1"], 0.28 if dark else 0.0)
    sel_text = "#FFFFFF"
    link = c["accent"]
    common = dict(ForegroundNormal=c["text"], ForegroundInactive=c["textDim"], ForegroundActive=c["accent"],
                  ForegroundLink=link, ForegroundVisited=_mix(link, "#B07BFF", 0.5),
                  ForegroundNegative=c["danger"], ForegroundNeutral=c["warning"], ForegroundPositive=c["success"],
                  DecorationFocus=c["accent"], DecorationHover=_mix(c["accent"], window, 0.35))
    groups = {
        "Window": dict(BackgroundNormal=window, BackgroundAlternate=_mix(window, c["text"], 0.03)),
        "Header": dict(BackgroundNormal=window, BackgroundAlternate=window),
        "View": dict(BackgroundNormal=view, BackgroundAlternate=_mix(view, c["text"], 0.025)),
        "Button": dict(BackgroundNormal=button, BackgroundAlternate=_mix(button, c["text"], 0.04)),
        "Tooltip": dict(BackgroundNormal=c["surface2"], BackgroundAlternate=c["surface2"]),
        "Complementary": dict(BackgroundNormal=c["bg"], BackgroundAlternate=c["surface0"]),
        "Selection": dict(BackgroundNormal=sel, BackgroundAlternate=_mix(sel, window, 0.4),
                          ForegroundNormal=sel_text, ForegroundInactive=_mix(sel_text, sel, 0.3),
                          ForegroundActive=sel_text, ForegroundLink=sel_text, ForegroundVisited=sel_text),
    }
    name = "X-OS Dark" if dark else "X-OS Light"
    out = ["# GENERATED by scripts/gen-theme.py from ui/theme/tokens.json - do not edit by hand.",
           "[ColorEffects:Disabled]", "Color=%s" % _c(c["surface1"]), "ColorAmount=0.55", "ColorEffect=3",
           "ContrastAmount=0.65", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", "",
           "[ColorEffects:Inactive]", "ChangeSelectionColor=true", "Color=%s" % _c(c["surface1"]),
           "ColorAmount=0.025", "ColorEffect=2", "ContrastAmount=0.1", "ContrastEffect=2", "Enable=false",
           "IntensityAmount=0", "IntensityEffect=0", ""]
    for g, vals in groups.items():
        merged = dict(common, **vals)
        out.append(f"[Colors:{g}]")
        out += [f"{k}={_c(v)}" for k, v in sorted(merged.items())]
        out.append("")
        if g == "Header":
            out.append("[Colors:Header][Inactive]")
            out += [f"{k}={_c(v)}" for k, v in sorted(merged.items())]
            out.append("")
    out += ["[General]", f"ColorScheme=XOS{mode.capitalize()}", f"Name={name}", "shadeSortColumn=true", "",
            "[KDE]", "contrast=4", "",
            "[WM]", f"activeBackground={_c(window)}", f"activeBlend={_c(window)}",
            f"activeForeground={_c(c['text'])}", f"inactiveBackground={_c(window)}",
            f"inactiveBlend={_c(window)}", f"inactiveForeground={_c(c['textDim'])}"]
    return "\n".join(out) + "\n"


def outputs() -> dict[Path, str]:
    return {OUT: generate(),
            SCHEMES / "XOSDark.colors": color_scheme("dark"),
            SCHEMES / "XOSLight.colors": color_scheme("light")}


def qcolor(hex_argb: str) -> str:
    return f'"{hex_argb}"'


def generate() -> str:
    t = json.loads(TOKENS.read_text())
    dark, light = t["color"]["dark"], t["color"]["light"]
    lines = [
        "// GENERATED by scripts/gen-theme.py from ui/theme/tokens.json — do not edit by hand.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        "    id: theme",
        "    // Appearance: \"dark\" (default) | \"light\". Set by the shell from the user's setting.",
        "    property string mode: \"dark\"",
        "    readonly property bool dark: mode !== \"light\"",
        "    // Reduced motion: every duration becomes 0 (set from the accessibility setting).",
        "    property bool reducedMotion: false",
        "    // Low-resource profile: no blur, no shadows (solid fallbacks).",
        "    property bool lowResource: false",
        "",
    ]
    for key in dark:
        lines.append(f"    readonly property color {key}: dark ? {qcolor(dark[key])} : {qcolor(light[key])}")
    lines.append("")
    for k, v in t["radius"].items():
        lines.append(f"    readonly property int radius{k.capitalize()}: {v}")
    for k, v in t["space"].items():
        lines.append(f"    readonly property int space{k.capitalize()}: {v}")
    ty = t["type"]
    lines += [
        f'    readonly property string fontFamily: "{ty["family"]}"',
        f'    readonly property string fontMono: "{ty["mono"]}"',
        f'    readonly property string fontRtl: "{ty["fallbackRtl"]}"',
    ]
    for k in ("caption", "body", "emphasis", "title", "display"):
        lines.append(f"    readonly property int font{k.capitalize()}: {ty[k]}")
    lines.append("")
    for k, v in t["bar"].items():
        lines.append(f"    readonly property real bar{k[0].upper()}{k[1:]}: {v}")
    lines.append("")
    for k, m in t["motion"].items():
        name = k[0].upper() + k[1:]
        lines.append(f"    readonly property int dur{name}: reducedMotion ? 0 : {m['ms']}")
        lines.append(f"    readonly property var curve{name}: [{', '.join(str(x) for x in m['bezier'])}, 1, 1]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    files = outputs()
    if "--check" in sys.argv:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"{p} is out of date: run scripts/gen-theme.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    (OUT.parent / "qmldir").write_text("module XOS.Theme\nsingleton Theme 1.0 Theme.qml\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
