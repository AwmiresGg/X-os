#!/usr/bin/env python3
"""Generate the QML Theme singleton from ui/theme/tokens.json.

    scripts/gen-theme.py          # writes ui/qml/XOS/Theme/Theme.qml
    scripts/gen-theme.py --check  # exit 1 if Theme.qml is out of date (used by tests)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "ui/theme/tokens.json"
OUT = ROOT / "ui/qml/XOS/Theme/Theme.qml"


def qcolor(hex_argb: str) -> str:
    return f'"{hex_argb}"'


def generate() -> str:
    t = json.loads(TOKENS.read_text())
    dark, light = t["color"]["dark"], t["color"]["light"]
    lines = [
        "// GENERATED by scripts/gen-theme.py from ui/theme/tokens.json — do not edit by hand.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        "    id: theme",
        "    // Appearance: \"dark\" (default) | \"light\". Set by the shell from the user's setting.",
        "    property string mode: \"dark\"",
        "    readonly property bool dark: mode !== \"light\"",
        "    // Reduced motion: every duration becomes 0 (set from the accessibility setting).",
        "    property bool reducedMotion: false",
        "    // Low-resource profile: no blur, no shadows (solid fallbacks).",
        "    property bool lowResource: false",
        "",
    ]
    for key in dark:
        lines.append(f"    readonly property color {key}: dark ? {qcolor(dark[key])} : {qcolor(light[key])}")
    lines.append("")
    for k, v in t["radius"].items():
        lines.append(f"    readonly property int radius{k.capitalize()}: {v}")
    for k, v in t["space"].items():
        lines.append(f"    readonly property int space{k.capitalize()}: {v}")
    ty = t["type"]
    lines += [
        f'    readonly property string fontFamily: "{ty["family"]}"',
        f'    readonly property string fontMono: "{ty["mono"]}"',
        f'    readonly property string fontRtl: "{ty["fallbackRtl"]}"',
    ]
    for k in ("caption", "body", "emphasis", "title", "display"):
        lines.append(f"    readonly property int font{k.capitalize()}: {ty[k]}")
    lines.append("")
    for k, v in t["bar"].items():
        lines.append(f"    readonly property real bar{k[0].upper()}{k[1:]}: {v}")
    lines.append("")
    for k, m in t["motion"].items():
        name = k[0].upper() + k[1:]
        lines.append(f"    readonly property int dur{name}: reducedMotion ? 0 : {m['ms']}")
        lines.append(f"    readonly property var curve{name}: [{', '.join(str(x) for x in m['bezier'])}, 1, 1]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date: run scripts/gen-theme.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    (OUT.parent / "qmldir").write_text("module XOS.Theme\nsingleton Theme 1.0 Theme.qml\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
